async function main() {
  const categoryIds = new Map()

  for (const category of categories) {
    const saved = await prisma.category.upsert({
      where: { slug: category.slug },
      update: {
        name: category.name,
        description: category.description,
      },
      create: category,
    })

    categoryIds.set(category.name, saved.id)
  }

  for (const product of products) {
    const categoryId = categoryIds.get(product.category)

    await prisma.product.upsert({
      where: { slug: product.slug },
      update: {
        name: product.name,
        description: product.description,
        price_ils: product.price_ils,
        imageUrl: product.imageUrl,
        categoryId,
        sun_exposure: product.sun_exposure,
        water_level: product.water_level,
        maintenance_level: product.maintenance_level,
        weight_level: product.weight_level,
        climate_zones: product.climate_zones,
        seasons: product.seasons,
        eco_score: product.eco_score,
        space_types: product.space_types,
        stock_quantity: product.stock_quantity,
        is_active: true,
      },
      create: {
        name: product.name,
        slug: product.slug,
        description: product.description,
        price_ils: product.price_ils,
        imageUrl: product.imageUrl,
        categoryId,
        sun_exposure: product.sun_exposure,
        water_level: product.water_level,
        maintenance_level: product.maintenance_level,
        weight_level: product.weight_level,
        climate_zones: product.climate_zones,
        seasons: product.seasons,
        eco_score: product.eco_score,
        space_types: product.space_types,
        stock_quantity: product.stock_quantity,
        is_active: true,
      },
    })
  }

  console.log(`Synced ${products.length} shop products.`)
}

main()
  .catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
